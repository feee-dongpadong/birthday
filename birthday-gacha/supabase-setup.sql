create table if not exists public.accounts (
  token text primary key,
  nickname text not null,
  created_at timestamptz not null default now(),
  last_seen timestamptz not null default now()
);

create table if not exists public.answers (
  id bigint generated by default as identity primary key,
  account_token text not null references public.accounts(token) on delete cascade,
  account_nickname text,
  round int not null default 1,
  star_name text,
  birthday text,
  wish text,
  created_at timestamptz not null default now()
);

create table if not exists public.draws (
  id bigint generated by default as identity primary key,
  account_token text not null references public.accounts(token) on delete cascade,
  account_nickname text,
  round int not null default 1,
  draw_index int not null,
  prize_rank int not null,
  prize_key text not null,
  prize_label text not null,
  prize_name text not null,
  best_rank int,
  created_at timestamptz not null default now()
);

create index if not exists idx_draws_account_round on public.draws (account_token, round);
create index if not exists idx_answers_account_round on public.answers (account_token, round);

alter table public.accounts enable row level security;
alter table public.answers enable row level security;
alter table public.draws enable row level security;

revoke all on public.accounts from anon, authenticated;
revoke all on public.answers from anon, authenticated;
revoke all on public.draws from anon, authenticated;

create or replace function public.fn_login(p_token text, p_nickname text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_nick text;
begin
  if p_token is null or length(p_token) < 8 then
    return jsonb_build_object('error', 'bad_token');
  end if;

  if p_nickname is null or length(btrim(p_nickname)) = 0 then
    return jsonb_build_object('error', 'bad_nickname');
  end if;

  insert into accounts (token, nickname)
  values (p_token, btrim(p_nickname))
  on conflict (token) do update set last_seen = now()
  returning nickname into v_nick;

  return jsonb_build_object('ok', true, 'nickname', v_nick);
end;
$$;

create or replace function public.fn_answer(
  p_token text,
  p_round int,
  p_name text,
  p_birthday text,
  p_wish text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_nick text;
begin
  select nickname into v_nick from accounts where token = p_token;

  if v_nick is null then
    return jsonb_build_object('error', 'account_not_found');
  end if;

  insert into answers (account_token, account_nickname, round, star_name, birthday, wish)
  values (p_token, v_nick, coalesce(p_round, 1), p_name, p_birthday, p_wish);

  return jsonb_build_object('ok', true);
end;
$$;

create or replace function public.fn_draw(p_token text, p_round int)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_nick text;
  v_used int;
  v_rank int;
  v_key text;
  v_label text;
  v_name text;
  v_best int;
  v_round int;
  v_roll numeric;
  v_has_first int;
begin
  v_round := coalesce(p_round, 1);

  select nickname into v_nick from accounts where token = p_token;

  if v_nick is null then
    return jsonb_build_object('error', 'account_not_found');
  end if;

  perform pg_advisory_xact_lock(hashtext(p_token || ':' || v_round));

  select count(*) into v_used
  from draws
  where account_token = p_token and round = v_round;

  if v_used >= 3 then
    return jsonb_build_object('error', 'no_chances');
  end if;

  if v_used = 2 then
    select count(*) into v_has_first
    from draws
    where account_token = p_token and round = v_round and prize_rank = 1;

    if v_has_first = 0 then
      v_rank := case when random() < 0.5 then 1 else 2 end;
    else
      v_roll := random();
      v_rank := case
        when v_roll < 0.25 then 1
        when v_roll < 0.60 then 2
        else 3
      end;
    end if;
  else
    v_roll := random();
    v_rank := case
      when v_roll < 0.25 then 1
      when v_roll < 0.60 then 2
      else 3
    end;
  end if;

  v_key := case v_rank when 1 then 'first' when 2 then 'second' else 'third' end;
  v_label := case v_rank when 1 then '一等奖' when 2 then '二等奖' else '三等奖' end;
  v_name := case v_rank
    when 1 then '288 元生日红包'
    when 2 then '精致 6 寸生日蛋糕'
    else '自助餐券一张'
  end;

  insert into draws (
    account_token, account_nickname, round, draw_index,
    prize_rank, prize_key, prize_label, prize_name
  ) values (
    p_token, v_nick, v_round, v_used + 1,
    v_rank, v_key, v_label, v_name
  );

  select min(prize_rank) into v_best
  from draws
  where account_token = p_token and round = v_round;

  update draws
  set best_rank = v_best
  where account_token = p_token and round = v_round;

  return jsonb_build_object(
    'draw_index', v_used + 1,
    'prize_rank', v_rank,
    'prize_key', v_key,
    'prize_label', v_label,
    'prize_name', v_name,
    'best_rank', v_best
  );
end;
$$;

grant execute on function public.fn_login(text, text) to anon;
grant execute on function public.fn_answer(text, int, text, text, text) to anon;
grant execute on function public.fn_draw(text, int) to anon;

create or replace view public.v_round_summary as
select
  account_nickname,
  account_token,
  round,
  count(*) as draws,
  min(prize_rank) as best_rank,
  case min(prize_rank)
    when 1 then '一等奖'
    when 2 then '二等奖'
    else '三等奖'
  end as best_label,
  min(created_at) as started_at,
  max(created_at) as last_draw_at
from public.draws
group by account_nickname, account_token, round;

